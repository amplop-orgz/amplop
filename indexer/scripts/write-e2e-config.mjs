// 16 S16-5: config.e2e.yaml for Anvil, generated from config.yaml and deployments/anvil.json so the
// event lists never drift. Spec 19 runs it before `envio --config config.e2e.yaml dev`.
import { writeFileSync } from "node:fs";
import { read } from "./lib.mjs";

const deploy = JSON.parse(read("../deployments/anvil.json"));
const [head] = read("config.yaml").split(/^chains:\n/m);
writeFileSync(
  new URL("../config.e2e.yaml", import.meta.url),
  `${head.replace(/^# Monad testnet.*\n#.*\n/m, "# Anvil, generated by scripts/write-e2e-config.mjs from config.yaml (16 S16-5). Do not edit.\n")}chains:
  - id: 31337
    start_block: 0
    rpc:
      - url: http://127.0.0.1:8545
        for: sync
    contracts:
      - name: AmplopEnvelopes
        address: "${deploy.address}"
`,
);
console.log("config.e2e.yaml written");
